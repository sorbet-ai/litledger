"""Token benchmark: scripted literature tasks with litledger vs. the usual web-fetch workflow.

Runs offline on the recorded test fixtures and writes docs/token-benchmark.md. "Without" numbers are conservative
lower bounds for an agent that fetches arXiv/abstract pages and writes BibTeX itself (no summarising fetch tool, no
retries). Token counts use the same offline estimate as the budget tests (~3.4 chars/token).

    python scripts/token_benchmark.py            # writes docs/token-benchmark.md and prints it
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "token-benchmark.md"
sys.path.insert(0, str(ROOT / "tests"))

from conftest import make_ledger  # noqa: E402

from litledger import tools  # noqa: E402
from litledger.db import Actor  # noqa: E402
from litledger.fulltext import current_document  # noqa: E402
from litledger.textutil import est_tokens  # noqa: E402

PAPERS = ["1706.03762", "10.18653/v1/N19-1423", "2412.06464", "2102.11174", "https://proceedings.mlr.press/v162/baevski22a.html"]

INTRO = """# Token benchmark

Generated by `scripts/token_benchmark.py`; rerun it after changing tool output or schemas. It runs four scripted tasks
offline against the recorded test fixtures and counts tokens with the same estimate as the budget tests (~3.4
chars/token). "With litledger" counts the agent's tool calls and what litledger returns. "Without" is a conservative
lower bound for an agent that reads the provider metadata or the paper itself and writes BibTeX by hand (no
summarising fetch tool, no retries, no searching).
"""


def schema_tokens(sets: list[str]) -> int:
    return est_tokens(json.dumps([{"name": n, "description": tools.TOOLS[n].description, "inputSchema": tools.mcp_schema(tools.TOOLS[n])}
                                  for n in tools.toolset_names(sets)]))


def main() -> None:
    lg = make_ledger(Path(tempfile.mkdtemp()))
    a = Actor(name="bench", kind="agent", project="bench")
    rows = []

    def call(name, **args):
        return tools.call(lg, a, name, args)

    # 1. Capture 5 papers and get their citekeys.
    with_tokens = est_tokens(json.dumps({"items": PAPERS, "add": True, "tags": ["phase:baselines"], "why": "baselines"}))
    with_tokens += est_tokens(call("resolve", items=PAPERS, add=True, tags=["phase:baselines"], why="baselines"))
    with lg.db.read() as conn:
        raw = sum(len(r["data"]) for r in conn.execute("SELECT data FROM work_sources"))
    without = est_tokens("x" * raw) // 2  # reading the metadata the providers returned (≈ half is markup)
    bib = call("export", tags=["phase:baselines"]).split("\n", 1)[1]
    without += est_tokens(bib)  # writing the BibTeX entries by hand (output tokens)
    rows.append(("Capture 5 papers (IDs/URL) with tags + keys", with_tokens, without))

    # 2. Next session: what did we capture for baselines?
    found = call("find", tags=["phase:baselines"])
    rows.append(("Recall tagged papers in a later session", est_tokens(found) + 15, est_tokens(bib) + est_tokens("why: baselines\n" * 5)))

    # 3. Pull one supporting quote from a paper.
    outline = call("read", work="yang2024gated")
    search = call("read", work="yang2024gated", mode="search", query="gating rapid memory erasure delta rule targeted updates")
    note = call("note", items=[{"work": "yang2024gated", "text": "complementary",
                                "quote": "gating enables rapid memory erasure while the delta rule facilitates targeted updates"}])
    with lg.db.read() as conn:
        doc = current_document(conn, conn.execute("SELECT id FROM works WHERE citekey='yang2024gated'").fetchone()["id"])
    rows.append((f"Find + anchor one quote in a {round(doc['chars'] / 1000)}k-char paper", est_tokens(outline + search + note) + 60,
                 est_tokens("x" * doc["chars"])))

    # 4. Bibliography for the paper draft.
    cli_line = "% 5 entries → refs.bib"
    rows.append(("Write refs.bib for the draft (CLI to file)", est_tokens(cli_line) + 20, est_tokens(bib)))

    lines = [INTRO,
             f"Tool schemas sent with every MCP request: ~{schema_tokens(['core'])} tokens for the default `core` toolset,\n"
             f"~{schema_tokens(['all'])} with every toolset (0 when an agent uses the CLI and the skill instead of MCP).\n",
             "| Task | with litledger | without (lower bound) | saving |",
             "|---|---:|---:|---:|"]
    lines += [f"| {task} | {w} | {wo} | {round(100 * (1 - w / wo))}% |" for task, w, wo in rows]
    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
